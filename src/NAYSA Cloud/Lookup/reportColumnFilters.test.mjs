import { strict as assert } from 'node:assert';
import { filterKind, isFilterActive, matchesColumnFilter as match, describeColumnFilter } from './reportColumnFilters.mjs';
assert.equal(match('Alpha', 'Alpha', 'PH'), true);
assert.equal(match('Alpha', 'Alpha', {operator:'startsWith',value:'al'}), true);
assert.equal(match('Alpha', 'Alpha', {operator:'endsWith',value:'ha'}), true);
assert.equal(match('Alpha', 'Alpha', {operator:'notContains',value:'al'}), false);
assert.equal(match(1000, '1,000.00', {operator:'greater',value:'999'}, 'number'), true);
assert.equal(match(0, '0.00', {operator:'equals',value:'0'}, 'number'), true);
assert.equal(match(null, '', {operator:'equals',value:'0'}, 'number'), false);
assert.equal(match('(100.00)', '(100.00)', {operator:'less',value:'0'}, 'number'), true);
assert.equal(match(20, '', {operator:'between',value:'10',endValue:'20'}, 'number'), true);
assert.equal(match(21, '', {operator:'between',value:'10',endValue:'20'}, 'number'), false);
assert.equal(match('2026-11-19T22:00:00', '', {operator:'equals',value:'2026-11-19'}, 'date'), true);
assert.equal(match('11/19/2026', '', {operator:'between',value:'2026-11-18',endValue:'2026-11-19'}, 'date'), true);
assert.equal(match('2026-02-31', '', {operator:'less',value:'2026-12-31'}, 'date'), false);
assert.equal(match('', '', {operator:'blank'}), true);
assert.equal(match(0, '0', {operator:'notBlank'}), true);
assert.equal(isFilterActive({operator:'blank'}), true);
assert.equal(isFilterActive(''), false);
assert.equal(isFilterActive(0), true);
assert.equal(filterKind({renderType:'currency'}), 'number');
assert.equal(filterKind({renderType:'date'}), 'date');
assert.equal(match(20, '', JSON.parse(JSON.stringify({operator:'greater',value:10})), 'number'), true);
assert.equal(match('Red Apple', 'Red Apple', {operator:'contains',value:'apple',values:['apple','pear'],match:'any'}), true);
assert.equal(match('Red Apple', 'Red Apple', {operator:'contains',value:'apple',values:['apple','pear'],match:'all'}), false);
assert.equal(match('Red Apple', 'Red Apple', {operator:'contains',value:'apple',values:['apple','RED'],match:'all'}), true);
assert.equal(match('Red Apple', 'Red Apple', {operator:'notContains',value:'pear',values:['pear','apple']}), false);
assert.equal(match('Red Apple', 'Red Apple', {operator:'notContains',value:'pear',values:['pear','banana']}), true);
assert.equal(describeColumnFilter({operator:'contains',value:'FGRR',values:['FGRR','FGSR'],match:'any'}), 'Contains: FGRR OR FGSR');
assert.equal(describeColumnFilter({operator:'contains',value:'A',values:['A','B'],match:'all'}), 'Contains: A AND B');
assert.equal(describeColumnFilter({operator:'between',value:1,endValue:10}), 'Between: 1 – 10');
console.log('29 report filter regression assertions passed.');
